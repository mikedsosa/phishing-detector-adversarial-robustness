"""Drift tables -> results/drift/DRIFT.md, results/drift/*.csv.

1. Time: PhreshPhish's own split is chronological (train 2024-07-02 to
   2025-09-08, test 2025-09-08 to 2025-12-16). Using the saved seed-42 models in
   ``models/phreshphish`` this reports, per test month, the detection rate on
   phishing and the false-positive rate on benign URLs (95% Wilson intervals),
   next to the same-period validation split (random rows from the training period).
2. Cross-dataset: false-positive rate and recall when a model trained on one
   dataset scores the other's test split, over every seed run in ``results/``.

Run ``python -m phishadv.drift`` after ``make reproduce-main`` (needs the saved models).
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from .aggregate import collect, find_runs
from .data import PHRESH_CSV, load_phreshphish, split
from .metrics import wilson_interval
from .models import load_detector
from .report import DATASET_LABELS, LABELS

MODELS = ("gbm_raw", "cnn_raw", "gbm_raw_at", "cnn_raw_at")


def _rate(k: int, n: int) -> str:
    if n == 0:
        return "-"
    lo, hi = wilson_interval(k, n)
    return f"{100 * k / n:.1f}% [{100 * lo:.1f}, {100 * hi:.1f}]"


def time_drift(models_dir: Path, seed: int = 42) -> pd.DataFrame:
    sp = split(load_phreshphish(PHRESH_CSV), seed, max_train=164759)
    val = sp.val.assign(period="validation (training period, random rows)")
    test = sp.test.assign(period="test " + sp.test.date.astype(str).str[:7])
    rows = []
    for name in MODELS:
        m, _ = load_detector(models_dir / name)
        for df in (val, test):
            p = m.predict_proba(df.url.tolist()) >= 0.5
            for period, g in df.assign(pred=p).groupby("period", sort=True):
                ph, bn = g[g.y == 1], g[g.y == 0]
                rows.append({"model": name, "period": period, "n_phish": len(ph), "n_benign": len(bn),
                             "detected": int(ph.pred.sum()), "false_pos": int(bn.pred.sum())})
    return pd.DataFrame(rows)


def write(root: Path = Path(".")) -> None:
    out = root / "results/drift"
    out.mkdir(parents=True, exist_ok=True)
    td = time_drift(root / "models/phreshphish")
    td.to_csv(out / "time_drift.csv", index=False)
    _, _, cross = collect(find_runs(root))
    cross.to_csv(out / "cross_dataset_by_seed.csv", index=False)

    lines = ["# Drift", "", "Generated by `python -m phishadv.drift`.", "",
             "## Over time (PhreshPhish, seed-42 models)", "",
             "PhreshPhish's train/test split is chronological: training URLs are dated 2024-07-02 to 2025-09-08 "
             "and test URLs 2025-09-08 to 2025-12-16. The validation rows are a random 10% of the training "
             "period. Brackets are 95% Wilson intervals. Class balance changes a lot by month (December has "
             "only benign URLs), so per-class rates are shown instead of F1.", "",
             "| Model | Period | Phishing detected | Benign flagged (FPR) | n phishing / benign |",
             "|---|---|---|---|---|"]
    for _, r in td.iterrows():
        lines.append(f"| {LABELS.get(r.model, r.model)} | {r.period} | {_rate(r.detected, r.n_phish)} | "
                     f"{_rate(r.false_pos, r.n_benign)} | {r.n_phish:,} / {r.n_benign:,} |")
    lines += ["", "## Across datasets (every seed run)", "",
              "Train on one dataset, score the other's test split. Mean [min-max] over seeds, two decimals so "
              "that near-total false-positive rates are not rounded to 100%.", "",
              "| Trained on | Tested on | Model | Seeds | FPR on legitimate URLs | Recall on phishing |",
              "|---|---|---|---|---|---|"]
    for (tr, ev, m), g in cross.groupby(["train_dataset", "eval_dataset", "model"], sort=False):
        f = lambda s: f"{100 * s.mean():.2f}% [{100 * s.min():.2f}-{100 * s.max():.2f}]"  # noqa: E731
        lines.append(f"| {DATASET_LABELS[tr]} | {DATASET_LABELS[ev]} | {LABELS.get(m, m)} | {len(g)} | "
                     f"{f(g.fpr)} | {f(g.recall)} |")
    lines.append("")
    (out / "DRIFT.md").write_text("\n".join(lines))
    print(f"wrote {out / 'DRIFT.md'}")



if __name__ == "__main__":
    write()
