"""Charts and a Markdown results table generated from ``results/summary.json``."""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402

LABELS = {
    "gbm_raw": "GBM (baseline)", "cnn_raw": "Char-CNN (baseline)",
    "gbm_canon": "GBM + canonicalization", "cnn_canon": "Char-CNN + canonicalization",
    "gbm_domain": "GBM, domain-only", "cnn_domain": "Char-CNN, domain-only",
    "gbm_raw_at": "GBM + adv. training", "cnn_raw_at": "Char-CNN + adv. training",
    "gbm_canon_at": "GBM + canon. + adv. training",
    "format_rule": "Format rule (not https://www.<domain>)",
    "query_rule": "Query rule (URL has a query string)",
}
ATTACK_LABELS = {
    "greedy_blackbox": "Greedy black-box", "random_blackbox": "Random transformations",
    "greedy_append_only": "Greedy black-box, append-only tier",
    "hotflip_whitebox": "HotFlip white-box (char flips)",
    "hybrid_whitebox": "Hybrid white-box (flips + transformations)",
    "shortener_wrap": "Link-shortener wrap (out of scope)",
    "greedy_heldout": "Greedy black-box, held-out transformations only",
    "beam_extended": "Beam search, all transformations, budget 20 (adaptive)",
}
DATASET_LABELS = {"phiusiil": "PhiUSIIL", "phreshphish": "PhreshPhish"}


# Hand-tuned label offsets so neighbouring points in the tradeoff chart stay readable.
_LABEL_OFFSETS = {"gbm_raw": (-6, -10), "cnn_raw": (-6, 6), "gbm_canon_at": (-6, 6), "cnn_canon": (5, -10)}
_LABEL_OFFSETS_BY_DATASET = {"phreshphish": {"gbm_raw": (-6, -10), "cnn_raw": (-6, -12), "cnn_canon": (-6, 6),
                                             "gbm_canon_at": (-6, 6), "cnn_raw_at": (-6, 6)}}


def _style(ax):
    ax.grid(alpha=0.3)
    ax.spines[["top", "right"]].set_visible(False)


def write_report(out: Path) -> None:
    out = Path(out)
    s = json.loads((out / "summary.json").read_text())
    curves = pd.read_csv(out / "evasion_vs_perturbations.csv")
    rob = pd.DataFrame(s["robustness"])
    clean = pd.read_csv(out / "clean_metrics.csv")
    ks = [c for c in curves.columns if c.startswith("k=")]
    xs = [int(c[2:]) for c in ks]

    # 1) evasion vs perturbation budget
    fig, axes = plt.subplots(1, 2, figsize=(13, 4.8))
    g = curves[curves.attack == "greedy_blackbox"]
    g = g[~g.model.str.endswith("domain")]
    for _, r in g.iterrows():
        ls = "-" if r.model.endswith("raw") else "--"
        axes[0].plot(xs, [100 * r[k] for k in ks], ls, marker="o", ms=3, label=LABELS.get(r.model, r.model))
    axes[0].set_title("Greedy black-box attack (owner tier)")
    axes[0].text(0.98, 0.02, "Domain-only models: 0% at every budget (not shown)", transform=axes[0].transAxes,
                 ha="right", va="bottom", fontsize=7.5, color="0.35")
    w = curves[curves.model == "cnn_raw"]
    for _, r in w.iterrows():
        axes[1].plot(xs, [100 * r[k] for k in ks], marker="o", ms=3, label=ATTACK_LABELS[r.attack])
    w2 = curves[(curves.model == "cnn_raw_at") & (curves.attack == "hybrid_whitebox")]
    for _, r in w2.iterrows():
        axes[1].plot(xs, [100 * r[k] for k in ks], "--", marker="o", ms=3,
                     label="Hybrid white-box vs. adv.-trained CNN")
    axes[1].set_title("Attacks on the character-level CNN")
    for ax in axes:
        ax.set_xlabel("Perturbation budget (transformations or character flips)")
        ax.set_ylabel("Evasion rate (% of detected phishing URLs)")
        ax.set_ylim(-2, 102)
        _style(ax)
        ax.legend(fontsize=7.5, loc="best")
    fig.tight_layout()
    fig.savefig(out / "evasion_vs_perturbations.png", dpi=150)
    plt.close(fig)

    # 2) clean accuracy vs robustness tradeoff
    gr = rob[rob.attack == "greedy_blackbox"].set_index("model")
    clean_models = clean[clean.model.isin(gr.index)]
    fig, ax = plt.subplots(figsize=(7.5, 5.2))
    for _, r in clean_models.iterrows():
        y = 100 * gr.loc[r.model, "detection_under_attack"]
        x = 100 * r.f1
        ax.scatter(x, y, s=55, color="#1f77b4" if r.model.startswith("gbm") else "#d62728")
        offsets = _LABEL_OFFSETS_BY_DATASET.get(s.get("data", {}).get("dataset"), _LABEL_OFFSETS)
        dx, dy = offsets.get(r.model, (5, 3))
        ax.annotate(LABELS.get(r.model, r.model), (x, y), fontsize=7.5, xytext=(dx, dy),
                    textcoords="offset points", ha="right" if dx < 0 else "left")
    ax.set_xlabel("Clean test F1 (%)")
    ax.set_ylabel("Phishing still detected under greedy attack (%)")
    ax.set_title("Clean performance vs. robustness (blue = GBM, red = Char-CNN)")
    _style(ax)
    fig.tight_layout()
    fig.savefig(out / "tradeoff.png", dpi=150)
    plt.close(fig)

    # 3) Markdown tables
    ds = DATASET_LABELS.get(s["data"].get("dataset", "phiusiil"), "PhiUSIIL")
    lines = [f"# Results: {ds}", "", f"Generated by `phishadv.experiment` (config `{s['config']['name']}`, "
             f"seed {s['config']['seed']}, runtime {s['runtime_seconds']} s).", "",
             f"Data: {s['data']['n_unique_urls']} unique URLs; train={s['data']['n_train']}, "
             f"val={s['data']['n_val']}, test={s['data']['n_test']}.", "",
             "## Clean test-set performance (phishing = positive class)", "",
             "| Model | Accuracy | Precision | Recall | F1 | ROC-AUC | FPR |", "|---|---|---|---|---|---|---|"]
    for _, r in clean.iterrows():
        lines.append(f"| {LABELS.get(r.model, r.model)} | {r.accuracy:.4f} | {r.precision:.4f} | "
                     f"{r.recall:.4f} | {r.f1:.4f} | {r.roc_auc:.4f} | {r.fpr:.4f} |")
    lines += ["", f"## Robustness (attack sample: {int(rob.n_sample.iloc[0])} phishing test URLs, "
              f"budget {s['config']['budget']})", "",
              "Evasion rate = share of the initially detected phishing URLs that the attack turns into a "
              "'legitimate' verdict (p < 0.5). Detection under attack = share of all sampled phishing URLs "
              "still flagged after the attack.", "",
              "| Model | Attack | Detected before | Evasion rate [95% Wilson CI] | Detection under attack "
              "| Median steps (successful) |",
              "|---|---|---|---|---|---|"]
    for _, r in rob.iterrows():
        ci = (f" [{r.evasion_ci95_low:.3f}, {r.evasion_ci95_high:.3f}]"
              if "evasion_ci95_low" in rob.columns and pd.notna(r.evasion_ci95_low) else "")
        lines.append(f"| {LABELS.get(r.model, r.model)} | {ATTACK_LABELS[r.attack]} | {r.n_initially_detected} | "
                     f"{r.evasion_rate:.3f}{ci} | {r.detection_under_attack:.3f} | {r.median_steps_successful} |")
    st = s["data"]["structure"]
    lines += ["", "## Dataset structure (all unique URLs)", "",
              "| Class | n | https | leading www | non-root path | query | bare https://www.<domain> |",
              "|---|---|---|---|---|---|---|"]
    for cls, d in st.items():
        lines.append(f"| {cls} | {d['n']} | {d['https']:.4f} | {d['leading_www']:.4f} | "
                     f"{d['non_root_path']:.4f} | {d['query']:.4f} | {d['bare_https_www']:.4f} |")
    h = s["hopskipjump_feature_space_gbm_raw"]
    lines += ["", "## Unconstrained feature-space attack (ART HopSkipJump on GBM baseline)", ""]
    lines += [f"- {k}: {v}" for k, v in h.items()]
    lines += ["", "## Transfer of greedy black-box adversarial URLs", "",
              "| Source | Target | n | Evasion on target |", "|---|---|---|---|"]
    for t in s["transfer"]:
        lines.append(f"| {t['source']} | {t['target']} | {t['n']} | {t['target_evasion_rate']:.3f} |")
    if s.get("cross_dataset"):
        xd = DATASET_LABELS.get(s["cross_dataset"][0]["eval_dataset"], "")
        lines += ["", f"## Cross-dataset: models trained here, scored on the {xd} test split", "",
                  "| Model | Precision | Recall | F1 | FPR |", "|---|---|---|---|---|"]
        for r in s["cross_dataset"]:
            lines.append(f"| {LABELS.get(r['model'], r['model'])} | {r['precision']:.4f} | {r['recall']:.4f} | "
                         f"{r['f1']:.4f} | {r['fpr']:.4f} |")
    lines += ["", "## Transformations used by successful greedy attacks", ""]
    for m, c in s["greedy_transformation_usage"].items():
        lines.append(f"- {m}: " + ", ".join(f"{k}: {v}" for k, v in sorted(c.items(), key=lambda kv: -kv[1])))
    ex_path = out / "adversarial_examples_greedy.csv"
    if ex_path.exists():
        ex = pd.read_csv(ex_path)
        ex = ex[(ex.final_p_phish < 0.5) & ex.model.isin(["gbm_raw", "cnn_raw_at"])]
        ex = ex.groupby("model", group_keys=False).head(4)
        lines += ["", "## Example successful evasions (defanged; do not visit)", "",
                  "| Model | Original | Adversarial | Final P(phishing) | Steps |", "|---|---|---|---|---|"]
        for _, r in ex.iterrows():
            lines.append(f"| {r.model} | `{defang(r.original)}` | `{defang(r.adversarial)}` | "
                         f"{r.final_p_phish:.3f} | {int(r.steps)} |")
    (out / "RESULTS.md").write_text("\n".join(lines) + "\n")


def defang(url: str) -> str:
    return url.replace("http", "hxxp", 1).replace(".", "[.]")
